"""Add NIH-original retention to the existing reviewed-import definition.

Preserve core action identities, bindings, mappings and human-field exclusions.
"""
from __future__ import annotations

import copy

SOURCE = "us-grants-gov-nih-pa-25-301"
ROLES = ["search-current", "detail-current", "search-replay", "detail-replay"]


def patch(definition: dict) -> dict:
    result = copy.deepcopy(definition)
    actions = result["actions"]
    if "Filter_NIH_Rows" in actions:
        raise ValueError("original retention already installed")
    trigger = result["triggers"]["manual"]
    trigger["inputs"]["schema"]["properties"]["OriginalResponsesJson"] = {
        "type": "string", "description": "Complete grants-originals-v1 envelope required for NIH rows; generated by grants_import_originals.py."}
    trigger["runtimeConfiguration"] = {"concurrency": {"runs": 1}}

    def node(kind, inputs, after=None, **extra):
        return {"type": kind, "runAfter": {after: ["Succeeded"]} if after else {}, "inputs": inputs, **extra}

    def guard(expression, after=None):
        return node("Compose", f"@if({expression},true,json('GRANTS_ORIGINALS_REJECTED'))", after)

    fields = ["Source", "SourceID", "RoundID", "OpportunityKey", "RetrievedUTC", "EvidenceHash"]
    schema = {"type": "object", "additionalProperties": False,
        "required": ["schema_version", *fields, "files"], "properties": {
            "schema_version": {"type": "string", "enum": ["grants-originals-v1"]},
            **{f: {"type": "string", "minLength": 1} for f in fields},
            "EvidenceHash": {"type": "string", "pattern": "^[0-9a-f]{64}$"},
            "files": {"type": "array", "minItems": 4, "maxItems": 14, "items": {
                "type": "object", "additionalProperties": False,
                "required": ["role", "sha256", "byte_length", "content_base64"], "properties": {
                    "role": {"type": "string", "maxLength": 80},
                    "sha256": {"type": "string", "pattern": "^[0-9a-f]{64}$"},
                    "byte_length": {"type": "integer", "minimum": 1, "maximum": 52428800},
                    "content_base64": {"type": "string", "minLength": 4,
                                       "pattern": "^[A-Za-z0-9+/]*={0,2}$"}}}}}}
    envelope = "body('Parse_Originals_Envelope')"
    first_row = "first(outputs('Parse_Reviewed_Rows'))"
    detail = f"json(base64ToString({envelope}?['files'][1]?['content_base64']))?['data']"
    validation = {
        "Parse_Originals_Envelope": node("ParseJson", {"content": "@json(coalesce(triggerBody()?['OriginalResponsesJson'],''))", "schema": schema}),
        "Guard_Originals_Binding": guard("and(equals(length(outputs('Parse_Reviewed_Rows')),1)," +
            ",".join(f"equals({envelope}?['{f}'],{first_row}?['{f}'])" for f in fields) + ")", "Parse_Originals_Envelope"),
        "Expected_Original_Roles": node("Select", {"from": "@" + detail + "?['synopsisAttachmentFolders']",
            "select": "@concat('attachment-folder-',string(item()?['id']))"}, "Guard_Originals_Binding"),
        "Submitted_Original_Roles": node("Select", {"from": "@" + envelope + "?['files']",
            "select": "@item()?['role']"}, "Expected_Original_Roles"),
        "Guard_Original_Roles": guard("equals(body('Submitted_Original_Roles'),union(createArray(" +
            ",".join(f"'{r}'" for r in ROLES) + "),body('Expected_Original_Roles')))", "Submitted_Original_Roles"),
        "Guard_Source_Projection": guard("and(" + ",".join([
            f"equals({detail}?['opportunityTitle'],{first_row}?['Title'])",
            f"equals({detail}?['synopsis']?['agencyName'],{first_row}?['Funder'])",
            f"equals({detail}?['synopsis']?['synopsisDesc'],{first_row}?['Description'])",
            f"equals({detail}?['synopsis']?['applicantEligibilityDesc'],{first_row}?['Eligibility'])",
            f"equals({detail}?['synopsis']?['fundingDescLinkDesc'],{first_row}?['URL'])",
            f"equals({detail}?['synopsis']?['responseDateStr'],json({first_row}?['SourceDateFactsJSON'])?['responseDateStr'])",
            f"equals({detail}?['synopsis']?['archiveDateStr'],json({first_row}?['SourceDateFactsJSON'])?['archiveDateStr'])",
        ]) + ")", "Guard_Original_Roles"),
        "Validate_Original_JSON": {"type": "Foreach", "foreach": "@take(" + envelope + "?['files'],4)",
            "runAfter": {"Guard_Source_Projection": ["Succeeded"]},
            "runtimeConfiguration": {"concurrency": {"repetitions": 1}}, "actions": {
                "Decode_Original_JSON": node("Compose", "@json(base64ToString(item()?['content_base64']))"),
                "Guard_Original_Source_Identity": guard("and(equals(outputs('Decode_Original_JSON')?['errorcode'],0),if(startsWith(item()?['role'],'search-'),and(equals(outputs('Decode_Original_JSON')?['data']?['hitCount'],1),equals(length(outputs('Decode_Original_JSON')?['data']?['oppHits']),1),equals(first(outputs('Decode_Original_JSON')?['data']?['oppHits'])?['id'],'357812'),equals(first(outputs('Decode_Original_JSON')?['data']?['oppHits'])?['number'],'PA-25-301')),and(equals(outputs('Decode_Original_JSON')?['data']?['id'],357812),equals(outputs('Decode_Original_JSON')?['data']?['opportunityNumber'],'PA-25-301'))))", "Decode_Original_JSON"),
            }},
    }
    actions["Filter_NIH_Rows"] = node("Query", {"from": "@outputs('Parse_Reviewed_Rows')",
        "where": f"@equals(item()?['Source'],'{SOURCE}')"}, "Parse_Reviewed_Rows")
    actions["Condition_Require_NIH_Originals"] = {"type": "If", "expression": "@greater(length(body('Filter_NIH_Rows')),0)",
        "runAfter": {"Filter_NIH_Rows": ["Succeeded"]}, "actions": validation, "else": {"actions": {}}}
    actions["Initialize_Row_Failure_Count"]["runAfter"] = {"Condition_Require_NIH_Originals": ["Succeeded"]}

    row_actions = actions["Apply_to_each_Reviewed_Row"]["actions"]["Condition_OpportunityKey_Present"]["actions"]
    conflict_else = row_actions["Condition_Conflicting_Source_Identity"]["else"]["actions"]
    new = conflict_else["Condition_Is_New_Opportunity"]
    base_inputs = copy.deepcopy(row_actions["SharePoint_Get_items"]["inputs"])

    def archive(prefix, record_id, after=None):
        def sp(op, params, after=None):
            inputs = {"host": {**base_inputs["host"], "operationId": op},
                "parameters": {"dataset": base_inputs["parameters"]["dataset"],
                               "table": base_inputs["parameters"]["table"], **params},
                "retryPolicy": {"type": "none"}}
            if "authentication" in base_inputs:
                inputs["authentication"] = copy.deepcopy(base_inputs["authentication"])
            return node("OpenApiConnection", inputs, after)

        name = prefix + "_Name"
        found = prefix + "_Found"
        add = prefix + "_Add_If_Missing"
        listing = prefix + "_List"
        reread = prefix + "_Readback_List"
        selected = prefix + "_Readback_File"
        unique = prefix + "_Require_One"
        content = prefix + "_Read_Content"
        file_actions = {
            name: node("Compose", "@concat('original-'," + envelope + "?['EvidenceHash'],'-',item()?['role'],if(startsWith(item()?['role'],'attachment-folder-'),'.zip','.json'))"),
            found: node("Query", {"from": "@body('" + listing + "')", "where": f"@equals(item()?['DisplayName'],outputs('{name}'))"}, name),
            add: {"type": "If", "expression": f"@equals(length(body('{found}')),0)", "runAfter": {found: ["Succeeded"]},
                "actions": {prefix + "_Create": sp("CreateAttachment", {"itemId": "@" + record_id,
                    "displayName": f"@outputs('{name}')", "body": "@base64ToBinary(item()?['content_base64'])"})}, "else": {"actions": {}}},
            reread: sp("GetItemAttachments", {"itemId": "@string(" + record_id + ")"}, add),
            selected: node("Query", {"from": f"@body('{reread}')", "where": f"@equals(item()?['DisplayName'],outputs('{name}'))"}, reread),
            unique: guard(f"equals(length(body('{selected}')),1)", selected),
            content: sp("GetAttachmentContent", {"itemId": "@" + record_id,
                "attachmentId": f"@first(body('{selected}'))?['Id']"}, unique),
            prefix + "_Verify_Bytes": guard(f"equals(body('{content}')?['$content'],item()?['content_base64'])", content),
        }
        return {"type": "If", "expression": f"@equals(items('Apply_to_each_Reviewed_Row')?['Source'],'{SOURCE}')",
            "runAfter": {after: ["Succeeded"]} if after else {}, "actions": {
                listing: sp("GetItemAttachments", {"itemId": "@string(" + record_id + ")"}),
                prefix + "_Files": {"type": "Foreach", "foreach": "@" + envelope + "?['files']",
                    "runAfter": {listing: ["Succeeded"]}, "runtimeConfiguration": {"concurrency": {"repetitions": 1}},
                    "actions": file_actions}}, "else": {"actions": {}}}

    new["actions"]["Archive_NIH_Create"] = archive("Original_Create", "body('SharePoint_Create_item')?['ID']", "SharePoint_Create_item")
    new["actions"]["SharePoint_Create_item_Preserve_ISO_Text"]["runAfter"] = {"Archive_NIH_Create": ["Succeeded"]}
    existing_archive = archive("Original_Update", "first(body('SharePoint_Get_items')?['value'])?['ID']", "Condition_Duplicate_OpportunityKey")
    existing_archive["expression"] = f"@and(equals(items('Apply_to_each_Reviewed_Row')?['Source'],'{SOURCE}'),equals(length(body('SharePoint_Get_items')?['value']),1))"
    conflict_else["Archive_NIH_Update"] = existing_archive
    new["runAfter"] = {"Archive_NIH_Update": ["Succeeded"]}
    return result
